# """
# Mock Data Population Script
# This script populates essential reference tables and generates simulated operational data
# for a complete working demo of the SomaiyaSat Telemetry Hub.
# It combines the existing data generation logic from `scripts/gen_data.py`
# and adds missing reference data (app_user, comm_mode, mission_phase, sensor, threshold_rule).
# Run with: `python scripts/mock_data.py`
# """

import sys
import os
import psycopg2
from psycopg2.extras import execute_values
from datetime import datetime

# Ensure project root in sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.db import get_conn
from scripts.gen_data import (
    reset_operational_data,
    run_mission_lifecycle_initialization,
    generate_downlink_windows_and_traffic,
    generate_telemetry_dataset,
)

def populate_reference_tables(conn):
    """Insert required reference data if not already present.
    This covers tables that are not regenerated by the main data generators.
    """
    with conn.cursor() as cur:
        # 1. mission_phase
        cur.execute("SELECT COUNT(*) FROM mission_phase;")
        if cur.fetchone()[0] == 0:
            phases = [
                (1, 'LAUNCH', 1, False),
                (2, 'DEPLOYED', 2, False),
                (3, 'COMMISSIONING', 3, False),
                (4, 'NOMINAL', 4, False),
                (5, 'SAFE_MODE', 5, True),
            ]
            execute_values(
                cur,
                "INSERT INTO mission_phase (phase_id, name, seq_no, tt_c_only) VALUES %s",
                phases,
            )

        # 2. comm_mode
        cur.execute("SELECT COUNT(*) FROM comm_mode;")
        if cur.fetchone()[0] == 0:
            modes = [
                (1, 'TTC', 1, 9600, 100),
                (2, 'SSTV', 2, 9600, 200),
                (3, 'CODEC2', 3, 8000, 150),
                (4, 'M17', 4, 8000, 150),
            ]
            execute_values(
                cur,
                "INSERT INTO comm_mode (mode_id, code, base_priority, bitrate_bps, tx_power_mw) VALUES %s",
                modes,
            )

        # 3. sensor
        cur.execute("SELECT COUNT(*) FROM sensor;")
        if cur.fetchone()[0] == 0:
            sensors = [
                (1, 'Battery Voltage', 'POWER', 'VOLTAGE', 'V'),
                (2, 'Battery Current', 'POWER', 'CURRENT', 'A'),
                (3, 'Solar Panel Voltage', 'POWER', 'VOLTAGE', 'V'),
                (4, 'Solar Current', 'POWER', 'CURRENT', 'A'),
                (5, 'Battery Temp', 'POWER', 'TEMP', 'C'),
                (6, 'Panel Temp +Y', 'THERMAL', 'TEMP', 'C'),
                (7, 'Panel Temp -Y', 'THERMAL', 'TEMP', 'C'),
                (8, 'OBC Core Temp', 'OBC', 'TEMP', 'C'),
                (9, 'OBC Supply Voltage', 'OBC', 'VOLTAGE', 'V'),
                (10, 'PA Temperature', 'RF', 'TEMP', 'C'),
                (11, 'RF Supply Voltage', 'RF', 'VOLTAGE', 'V'),
                (12, 'TX Current', 'RF', 'CURRENT', 'A'),
            ]
            execute_values(
                cur,
                "INSERT INTO sensor (sensor_id, name, subsystem, sensor_type, unit) VALUES %s",
                sensors,
            )

        # 4. threshold_rule (warning & critical for each sensor)
        cur.execute("SELECT COUNT(*) FROM threshold_rule;")
        if cur.fetchone()[0] == 0:
            rules = []
            # Battery Voltage thresholds (critical low, warning low)
            rules.extend([
                (1, 1, 3.30, 4.20, 'CRITICAL'),
                (1, 2, 3.50, 4.20, 'WARNING'),
                (1, 3, 0, 5.00, 'WARNING'),
            ])
            # Generic warning range for other sensors
            for sid in range(2, 13):
                rules.append((sid, 1, -40, 85, 'WARNING'))
            execute_values(
                cur,
                "INSERT INTO threshold_rule (sensor_id, rule_no, min_val, max_val, severity) VALUES %s",
                rules,
            )

        # 5. app_user (basic operator and admin accounts)
        cur.execute("SELECT COUNT(*) FROM app_user;")
        if cur.fetchone()[0] == 0:
            users = [
                (1, 'admin', 'ADMIN', None),
                (2, 'ops_asha', 'OPERATOR', 'ASHA'),
                (3, 'ham_john', 'HAM_VOLUNTEER', 'JOHN'),
                (4, 'viewer_jane', 'VIEWER', None),
            ]
            execute_values(
                cur,
                "INSERT INTO app_user (user_id, username, role, callsign) VALUES %s",
                users,
            )

        conn.commit()
        print("Reference tables populated.")


def main():
    print("=== SomaiyaSat Mock Data Population ===")
    conn = get_conn()
    try:
        populate_reference_tables(conn)
        reset_operational_data(conn)
        run_mission_lifecycle_initialization(conn)
        generate_downlink_windows_and_traffic(conn, target_windows=300)
        generate_telemetry_dataset(conn, samples_per_sensor=8350)
        print("All mock data generated successfully.")
    finally:
        conn.close()

if __name__ == "__main__":
    main()
